const directory = new URL("../packages/ui-tokens/src/brand-logos/", import.meta.url);
async function get(url) {
  const response = await fetch(url, { signal: AbortSignal.timeout(30_000) });
  if (!response.ok) throw new Error(`SVGL download failed: ${response.status}`);
  return response;
}
const catalog = await (await get("https://api.svgl.app")).json();
const registry = {};
const artwork = {};
for (const item of catalog) {
  const routes =
    typeof item.route === "string" ? { light: item.route, dark: item.route } : item.route;
  for (const route of Object.values(routes)) {
    if (!route.startsWith("https://svgl.app/library/") || !route.endsWith(".svg")) {
      throw new Error("Unexpected SVGL asset URL");
    }
  }
  const key = item.title.toLowerCase().replace(/[^a-z0-9]/g, "");
  registry[key] = routes;
  if (!bundled.has(item.title)) continue;
  artwork[key] = {};
  for (const [appearance, route] of Object.entries(routes)) {
    const xml = await (await get(route)).text();
    if (
      !xml.includes("<svg") ||
      /<(script|foreignObject|image)\b|\bon\w+\s*=|(?:href|url)\s*[=(]\s*["']?https?:/i.test(xml)
    ) {
      throw new Error(`Unexpected active SVG content: ${item.title}`);
    }
    artwork[key][appearance] = xml;
  }
}
await mkdir(directory, { recursive: true });
await writeFile(
  new URL("catalog.ts", directory),
  `// Generated by scripts/generate-svgl-logos.mjs. See LICENSE and README.md.\nexport const svglCatalog: Record<string, { light: string; dark: string }> = ${JSON.stringify(registry, null, 2)};\n`,
);
await writeFile(
  new URL("artwork.ts", directory),
  `// Generated by scripts/generate-svgl-logos.mjs. See LICENSE and README.md.\nexport const svglArtwork: Record<string, { light: string; dark: string }> = ${JSON.stringify(artwork, null, 2)};\n`,
);
await writeFile(
  new URL("LICENSE", directory),
  await (await get("https://raw.githubusercontent.com/pheralb/svgl/main/LICENSE")).text(),
);
console.log(
  `Bundled ${Object.keys(artwork).length} brands; indexed ${Object.keys(registry).length} SVGL logos.`,
);
